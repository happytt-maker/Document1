def norm(s):
    """归一化：全角→半角、去所有空白、统一小写（比较前两边都过一遍）。"""
    if not s:
        return ""
    s = unicodedata.normalize("NFKC", s)
    return "".join(ch for ch in s if not ch.isspace()).lower()


def lev(a, b):
    """编辑距离（滚动数组）。"""
    if a == b:
        return 0
    if not a:
        return len(b)
    if not b:
        return len(a)
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]


def score(name, text):
    """对一张图算分：返回 dict(hit, key, miss, cer, chars)。"""
    keys = GROUND_TRUTH.get(name) or []
    nt = norm(text)
    hits = [k for k in keys if norm(k) in nt]
    miss = [k for k in keys if norm(k) not in nt]
    exp = norm(FULL_TEXT.get(name, ""))
    cer = (1 - lev(nt, exp) / len(exp)) if exp else 0.0
    return {"hit": len(hits), "key": len(keys), "miss": miss,
            "cer": cer, "chars": len(nt)}
